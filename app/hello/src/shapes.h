/// Identifies the simple shapes implemented by this application. The values double as indices into the applet's shape
/// list.
enum class SimpleShapes
{
	/// A flat convex polygon, see \c ConvexPolygon.
	ConvexPolygon,

	/// A flat-shaded platonic solid, see \c PlatonicSolid.
	PlatonicSolid,

	/// The number of shapes. Not a valid shape.
	NUM
};

/// Shortcut alias for <tt>\ref SimpleShapes "SimpleShapes"</tt>.
using SS = SimpleShapes;



//////
//
// Classes
//

/// \brief
/// 	Abstract base class of all simple shapes: a procedurally generated, indexed mesh with its own GUI parameters
/// 	and GPU buffers.
///
/// A concrete shape generates its geometry on the CPU in \c regenerate and exposes it through \c vertices,
/// \c indices and <tt>corners</tt>. The base class takes care of uploading the mesh to GPU buffers. Call \c update
/// once per frame (e.g. from \c Applet::update) to regenerate and upload the geometry whenever a parameter has
/// changed, then draw \c numIndices indices from \c indexBuffer and \c vertexBuffer as \c primitiveType primitives.
///
/// A new shape starts out dirty, so its geometry is generated by the first call to \c update.
class SimpleShape
{
public:

	////
	// Types

	/// The vertex layout shared by all simple shapes: interleaved position and normal, both as \c glm::vec4.
	struct Vertex
	{
		/// The homogeneous object-space position. Its \c w component is 1.
		glm::vec4 position;

		/// The object-space unit normal. Its \c w component is 0.
		glm::vec4 normal;
	};


	////
	// Object construction/destruction

	/// \brief Destroys the shape and releases its GPU buffers.
	///
	/// \pre The \c fcg::Device last passed to \c update must still be alive.
	virtual ~SimpleShape();


	////
	// Accessors

	/// \brief Returns the human-readable name of this shape, e.g. for display in the GUI.
	///
	/// \return A null-terminated string that remains valid for the lifetime of the shape.
	[[nodiscard]] virtual auto name () const -> const char* = 0;

	/// \brief Returns the primitive type that this shape's index data is meant to be drawn with.
	///
	/// \return The SDL GPU primitive type to use in the graphics pipeline.
	[[nodiscard]] virtual auto primitiveType () const -> SDL_GPUPrimitiveType = 0;

	/// \brief Returns the CPU-side vertex data generated by the last call to \c regenerate.
	///
	/// \return A view of the vertices that is valid until the next call to \c regenerate or destruction of the shape.
	[[nodiscard]] virtual auto vertices () const -> std::span<const Vertex> = 0;

	/// \brief Returns the CPU-side index data generated by the last call to \c regenerate.
	///
	/// \return
	/// 	A view of the 32-bit indices into \c vertices that is valid until the next call to \c regenerate or
	/// 	destruction of the shape.
	[[nodiscard]] virtual auto indices () const -> std::span<const uint32_t> = 0;

	/// \brief Returns one homogeneous object-space position per geometric corner, with \c w equal to 1.
	///
	/// Shared corners occur once even when several mesh vertices have the same position and different normals.
	///
	/// \return
	/// 	A borrowed view generated by the last call to <tt>regenerate</tt>, valid until the next regeneration or
	/// 	destruction of the shape. The view is empty before the first regeneration.
	[[nodiscard]] virtual auto corners () const -> std::span<const glm::vec4> = 0;

	/// \brief Reports whether the shape's parameters have changed since its geometry was last uploaded.
	///
	/// \return \c true if the next call to \c update will regenerate and upload the geometry.
	[[nodiscard]] inline auto dirty () const -> bool {
		return m_dirty;
	}

	/// \brief Returns the GPU vertex buffer holding the most recently uploaded geometry.
	///
	/// \return
	/// 	A pointer to the vertex buffer owned by this shape, or \c nullptr before the first successful upload and
	/// 	after empty geometry was uploaded. The pointer stays valid until the next successful upload in \c update
	/// 	or destruction of the shape.
	[[nodiscard]] inline auto vertexBuffer () const -> const fcg::Buffer* {
		return m_geometry ? &m_geometry->vertices : nullptr;
	}

	/// \brief
	/// 	Returns the GPU index buffer holding the most recently uploaded geometry. The indices are 32-bit unsigned
	/// 	integers.
	///
	/// \return
	/// 	A pointer to the index buffer owned by this shape, or \c nullptr before the first successful upload and
	/// 	after empty geometry was uploaded. The pointer stays valid until the next successful upload in \c update
	/// 	or destruction of the shape.
	[[nodiscard]] inline auto indexBuffer () const -> const fcg::Buffer* {
		return m_geometry ? &m_geometry->indices : nullptr;
	}

	/// \brief Returns the number of indices in \c indexBuffer.
	///
	/// \return The number of uploaded indices, or 0 if there is no GPU geometry to draw.
	[[nodiscard]] inline auto numIndices () const -> std::size_t {
		return m_geometry ? m_geometry->numIndices : 0;
	}


	////
	// Methods

	/// Shows the shape-specific parameter widgets in the current Dear ImGui window. Call from \c Applet::gui between
	/// \c ImGui::Begin and \c ImGui::End. Implementations call \c markDirty whenever a parameter changes.
	virtual void gui () = 0;

	/// Regenerates the CPU-side geometry returned by \c vertices, \c indices and \c corners from the current parameters.
	/// Normally called by \c update rather than directly.
	virtual void regenerate () = 0;

	/// \brief Regenerates and uploads the geometry if the shape is \c dirty, and does nothing otherwise.
	///
	/// Call once per frame from \c Applet::update. On success, the shape is no longer dirty and \c vertexBuffer,
	/// \c indexBuffer and \c numIndices refer to the new geometry. If the upload fails, the error is logged, the
	/// previously uploaded geometry stays in place and the shape remains dirty, so the next call tries again. The
	/// upload is submitted to the GPU without waiting for it to complete.
	///
	/// \pre Always pass the same device. The device must outlive the shape.
	///
	/// \param device The device on which to create the GPU buffers.
	inline void update (fcg::Device &device)
	{
		if (dirty()) {
			regenerate();
			if (uploadGeometry(device, vertices(), indices()))
				clearDirty();
		}
	}


protected:

	////
	// State management

	/// Marks the shape as dirty, so that the next call to \c update regenerates and uploads its geometry.
	/// Implementations call this whenever a parameter changes.
	inline void markDirty () {
		m_dirty = true;
	}

	/// Clears the dirty flag. Called by \c update after the regenerated geometry was uploaded successfully.
	inline void clearDirty () {
		m_dirty = false;
	}

	/// \brief Replaces the shape's GPU geometry with the given vertex and index data.
	///
	/// Both GPU buffers are created and uploaded together. They only replace the current geometry once the upload has
	/// been submitted successfully, so on failure the previous geometry stays in place. If either span is empty, the
	/// current GPU geometry is released and the call succeeds without allocating anything. Errors are logged.
	///
	/// \pre Always pass the same device. The device must outlive the shape.
	///
	/// \param device The device on which to create the GPU buffers.
	/// \param vertices The vertex data. It is copied before the function returns.
	/// \param indices The 32-bit indices into \p vertices. They are copied before the function returns.
	///
	/// \return
	/// 	\c true on success (including empty geometry), or \c false if creating or uploading the buffers failed, or
	/// 	if a different device was passed than the one holding the current geometry.
	[[nodiscard]] auto uploadGeometry (
		fcg::Device &device, std::span<const Vertex> vertices, std::span<const std::uint32_t> indices
	) -> bool;


private:

	////
	// Types

	/// One successfully submitted geometry replacement. Both buffers are always present and committed together.
	struct Geometry
	{
		/// The owned vertex buffer.
		fcg::Buffer vertices;

		/// The owned index buffer, holding 32-bit indices.
		fcg::Buffer indices;

		/// The number of indices in the index buffer. Never zero for committed geometry.
		std::size_t numIndices;
	};


	////
	// Fields

	/// Whether the parameters changed and the geometry needs to be regenerated and uploaded.
	bool m_dirty = true;

	/// Reusable upload batch, created by the first non-empty upload and bound to the device passed there.
	std::optional<fcg::UploadBatch> uploads;

	/// The current GPU geometry. Only present after a non-empty upload succeeded. A failed replacement keeps the
	/// previous value, and an empty replacement resets it.
	std::optional<Geometry> m_geometry;
};


#endif  // __FCG_HELLO_SHAPES_H__
