
#ifndef __FCG_HELLO_CONVEX_POLY_H__
#define __FCG_HELLO_CONVEX_POLY_H__


//////
//
// Includes
//

// C++ STL
#include <cmath>
#include <vector>

// Dear ImGui
#include <imgui.h>

// Local includes
#include "shapes.h"



//////
//
// Classes
//

/// \brief A flat, regular convex polygon in the \e xy-plane, centered at the origin and facing the positive \e z-axis.
///
/// The vertices are distributed evenly on a circle of configurable radius, counter-clockwise when viewed from the
/// positive \e z-axis, starting at <tt>(radius, 0, 0)</tt>. The polygon is triangulated as a fan around the first
/// vertex and drawn as a triangle list. All vertices share the normal <tt>(0, 0, 1)</tt>. The GUI offers between 3 and
/// 64 vertices and a radius between 0.001 and 100.
class ConvexPolygon : public SimpleShape
{
public:

	////
	// Object construction

	/// Constructs an equilateral triangle with radius 1.
	ConvexPolygon() = default;


	////
	// Interface: SimpleShape

	/// \brief Returns the display name of this shape.
	///
	/// \return The string <tt>"Convex Polygon"</tt>.
	[[nodiscard]] auto name () const -> const char* override {
		return "Convex Polygon";
	}

	/// Shows widgets for the number of vertices and the radius, plus buttons for common presets.
	void gui () override
	{
		bool changed = false;

		if (ImGui::SliderInt("Vertices", &numVertices, minVertices, maxVertices))
			changed = true;

		if (ImGui::DragFloat("Radius", &radius, 0.01f, 0.001f, 100.0f, "%.3f"))
			changed = true;

		if (ImGui::Button("Triangle")) {
			numVertices = 3;
			changed = true;
		}
		ImGui::SameLine();
		if (ImGui::Button("Quad")) {
			numVertices = 4;
			changed = true;
		}
		ImGui::SameLine();
		if (ImGui::Button("Hexagon")) {
			numVertices = 6;
			changed = true;
		}

		if (changed)
			markDirty();
	}

	/// Generates the polygon's vertices and triangle-list indices from the current parameters.
	void regenerate () override
	{
		// Prepare storage
		m_vertices.clear();
		m_indices.clear();
		const auto n = size_t(numVertices);
		m_vertices.reserve(n);

		// Generate vertices
		constexpr float twoPi = 2*3.14159265358979f;
		for (size_t i=0; i<n; ++i)
		{
			const float angle = twoPi * static_cast<float>(i) / static_cast<float>(n);
			m_vertices.push_back(Vertex{
				.position = glm::vec4(radius * std::cos(angle), radius * std::sin(angle), .0f, 1.f),
				.normal = glm::vec4(.0f, .0f, 1.f, .0f)
			});
		}

		// Generate triangle list indices in a fan-like pattern: (0, i, i+1) for i = 1..n-2. SDL GPU has no triangle fan
		// primitive type, so the fan is expanded into a list.
		for (uint32_t i=1; i+1<n; ++i) {
			m_indices.push_back(0);
			m_indices.push_back(i);
			m_indices.push_back(i+1);
		}
	}

	/// \brief Returns the primitive type of the polygon's index data.
	///
	/// \return Always \c SDL_GPU_PRIMITIVETYPE_TRIANGLELIST.
	[[nodiscard]] auto primitiveType () const -> SDL_GPUPrimitiveType override {
		return SDL_GPU_PRIMITIVETYPE_TRIANGLELIST;
	}

	/// \brief Returns the vertices generated by the last call to \c regenerate.
	///
	/// \return A view that is valid until the next call to \c regenerate or destruction of the shape.
	[[nodiscard]] auto vertices () const -> std::span<const Vertex> override {
		return m_vertices;
	}

	/// \brief Returns the triangle-list indices generated by the last call to \c regenerate.
	///
	/// \return A view that is valid until the next call to \c regenerate or destruction of the shape.
	[[nodiscard]] auto indices () const -> std::span<const uint32_t> override {
		return m_indices;
	}


private:

	////
	// Constants

	/// The smallest number of vertices offered by the GUI.
	static constexpr unsigned minVertices = 3;

	/// The largest number of vertices offered by the GUI.
	static constexpr unsigned maxVertices = 64;


	////
	// Fields

	/// The number of vertices on the polygon perimeter, as an \c int for use with Dear ImGui.
	int numVertices = 3;

	/// The radius of the circle the vertices lie on.
	float radius = 1.0f;

	/// The CPU-side vertex data.
	std::vector<Vertex> m_vertices;

	/// The CPU-side triangle-list index data.
	std::vector<uint32_t> m_indices;
};


#endif  // __FCG_HELLO_CONVEX_POLY_H__
